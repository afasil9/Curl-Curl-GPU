std::vector<double> fold_reference(const std::vector<double>& refs,
                                   const std::vector<double>& T,
                                   const std::vector<double>& Tt,
                                   int n_class, int nd)
{

    // folded[p][k][i][j]  =  folded[((p * 12 + k) * nd + i) * nd + j]
    // p perm class, k = 0..5 for curl-curl then 6..11 for mass, i = Test basis functions, j = Trial basis functions
    std::vector<double> folded(n_class * 12 * nd * nd, 0.0); // result: (n_class, 12, nd, nd)
    std::vector<double> tmp(nd * nd, 0.0);                        // scratch: one nd x nd matrix



    for (int k = 0; k < 12; ++k){ // Loop over 6 curl then 6 mass
        for (int p = 0; p < n_class; ++p){
            // tmp = T_p · R[k]
            std::fill(tmp.begin(), tmp.end(), 0.0);
            for (int rows_tp = 0; rows_tp < nd; ++rows_tp){
                for (int cols_rk = 0; cols_rk < nd; ++cols_rk){
                    for (int m = 0; m < nd; ++m){
                        // Tp [i][m] = T[p * nd * nd + i * nd + m]
                        // Rk [m][j] = refs[k * nd * nd + m * nd + j]
                        // tmp[i][j] = Σₘ Tp[i][m] * Rk[m][j]
                        tmp[rows_tp * nd + cols_rk] += T[p * nd * nd + rows_tp * nd + m] *
                                                       refs[k * nd * nd + m * nd + cols_rk];
                    }
                }
            }

            // folded[p][k] = tmp · Tt_p  (same p and k, while tmp still holds T_p · R[k])
            for (int rows_tp = 0; rows_tp < nd; ++rows_tp){
                for (int cols_rk = 0; cols_rk < nd; ++cols_rk){
                    for (int m = 0; m < nd; ++m){
                        // tmp [i][m] = tmp[i * nd + m]
                        // Tt [m][j] = Tt[p * nd * nd + m * nd + j]
                        // folded[p][k][i][j] = Σₘ tmp[i][m] * Tt[m][j]
                        folded[((p * 12 + k) * nd + rows_tp) * nd + cols_rk] +=
                            tmp[rows_tp * nd + m] * Tt[p * nd * nd + m * nd + cols_rk];
                    }
                }
            }
        }
    }
    return folded;
}


std::vector<double> matvec(const std::vector<double>& x, const std::vector<double>& coeffs, const permutation_class& pc, int nd, const std::vector<double>& folded, auto dofmap)
{

    //dofmap = (n_cells, nd)
    const std::size_t n_cells = pc.clas.size();
    std::vector<double> y_vec(x.size(), 0.0);

    for (std::size_t c = 0; c < n_cells; ++c){
        int p = pc.clas[c]; // permutation class of cell c
        for (int k = 0; k < 12; ++k){ // Loop over 6 curl then 6 mass
            for (int i = 0; i < nd; ++i){ // Test basis functions
                double sum = 0.0;
                for (int j = 0; j < nd; ++j){ // Trial basis functions
                    sum += folded[((p * 12 + k) * nd + i) * nd + j] * x[(dofmap(c, j))];
                }
                y_vec[dofmap(c, i)] += coeffs[12 * c + k] * sum;
            }
        }
    }
    return y_vec;
    }


std::vector<double> getdiagonal(const std::vector<double>& coeffs, const permutation_class& pc, int nd, const std::vector<double>& folded, auto dofmap, int ndofs)
{
    const std::size_t n_cells = pc.clas.size();
    std::vector<double> diagonal(ndofs, 0.0);

    for (std::size_t c = 0; c < n_cells; ++c){
        int p = pc.clas[c]; // permutation class of cell c
        for (int k = 0; k < 12; ++k){ // Loop over 6 curl then 6 mass
            for (int i = 0; i < nd; ++i){ // Test basis functions
                double sum = 0.0;
                sum += folded[((p * 12 + k) * nd + i) * nd + i];
                diagonal[dofmap(c, i)] += coeffs[12 * c + k] * sum;
            }
        }
    }
    return diagonal;
}

// Boundary mask: bc_mask[g] = 1.0 if global dof g lies on the boundary, else 0.0.
std::vector<double> boundary_dof_mask(auto msh, auto V, std::int32_t ndofs)
{
    const int tdim = msh->topology()->dim();
    auto topology = msh->topology_mutable();
    topology->create_entities(tdim - 1);          // facets
    topology->create_connectivity(tdim - 1, tdim); // facet -> cell (to find exterior facets)
    topology->create_connectivity(tdim, tdim - 1); // cell -> facet (to find dofs on facets)

    const std::vector<std::int32_t> facets = dolfinx::mesh::exterior_facet_indices(*topology);
    const std::vector<std::int32_t> bdofs = dolfinx::fem::locate_dofs_topological(
        *topology, *V->dofmap(), tdim - 1, std::span<const std::int32_t>(facets));

    std::vector<double> bc_mask(ndofs, 0.0);
    // Mark the boundary dofs as 1.0 in mask. bc_mask[g] = 1.0 if dof g lies on a boundary edge or face
    for (std::int32_t g : bdofs)
        if (g < ndofs)
            bc_mask[g] = 1.0;
    return bc_mask;
}


std::vector<double> matvec_bc(const std::vector<double>& x,
                              const std::vector<double>& bc_mask,
                              const std::vector<double>& coeffs,
                              const permutation_class& pc, int nd,
                              const std::vector<double>& folded, auto dofmap)
{
    std::vector<double> x_in = x;

    for (std::size_t g = 0; g < x.size(); ++g)
    if (bc_mask[g] == 1.0)
        x_in[g] = 0.0; // Zero out the boundary dofs in the input vector
    std::vector<double> y = matvec(x_in, coeffs, pc, nd, folded, dofmap);

    for (std::size_t g = 0; g < y.size(); ++g)
        if (bc_mask[g] == 1.0)
        y[g] = x[g];

    return y;
}

std::vector<double> diagonal_bc(const std::vector<double>& bc_mask,
                                const std::vector<double>& coeffs,
                                const permutation_class& pc, int nd,
                                const std::vector<double>& folded, auto dofmap, int ndofs)
{
    std::vector<double> d = getdiagonal(coeffs, pc, nd, folded, dofmap, ndofs);

    for (std::size_t g = 0; g < d.size(); ++g)
    {
        if (bc_mask[g] == 1.0)
            d[g] = 1.0; // boundary row is all zeros except a 1 on the diagonal
    }
    return d;
}


std::vector<double> fold_interpolation(const std::vector<double>& interp_ref, const std::vector<double>& Ts, const std::vector<double>& Td, int n_class, int nd_low, int nd_high)
{
    // interp_ref: (high, low) for each permutation class

    // folded[p][i][j] = folded[((p * nd_high + i) * nd_low + j)]
    std::vector<double> folded(n_class * nd_high * nd_low, 0.0);

    for (int p = 0; p < n_class; ++p)
    {
        // tmp = Td_p · interp_ref
        std::vector<double> tmp(nd_high * nd_low, 0.0);
        for (int rows_td = 0; rows_td < nd_high; ++rows_td)
        {
            for (int cols_br = 0; cols_br < nd_low; ++cols_br)
            {
                for (int m = 0; m < nd_high; ++m)
                {
                    tmp[rows_td * nd_low + cols_br] += Td[p * nd_high * nd_high + rows_td * nd_high + m] *
                                                       interp_ref[m * nd_low + cols_br];
                }
            }
        }

        // folded[p] = tmp · Ts_p
        for (int rows_tmp = 0; rows_tmp < nd_high; ++rows_tmp)
        {
            for (int cols_ts = 0; cols_ts < nd_low; ++cols_ts)
            {
                for (int m = 0; m < nd_low; ++m)
                {
                    folded[(p * nd_high + rows_tmp) * nd_low + cols_ts] +=
                        tmp[rows_tmp * nd_low + m] * Ts[p * nd_low * nd_low + m * nd_low + cols_ts];
                }
            }
        }
    }
    return folded;
}


std::vector<double> apply_transfer(const std::vector<double>& x_low, const std::vector<double>& interp_folded, const permutation_class& pc, int nd_low, int nd_high, auto dofmap_low, auto dofmap_high, std::int32_t ndofs_high)
{
    const std::size_t n_cells = pc.clas.size();
    std::vector<double> x_high(ndofs_high, 0.0);
    std::vector<double> mult(ndofs_high, 0.0); // how many cells contain each high-order dof

    for (std::size_t c = 0; c < n_cells; ++c)
    {
        int p = pc.clas[c]; // permutation class of cell c
        for (int i = 0; i < nd_high; ++i) // Test basis functions in high-order space
        {
            double sum = 0.0;
            for (int j = 0; j < nd_low; ++j) // Trial basis functions in low-order space
            {
                sum += interp_folded[(p * nd_high + i) * nd_low + j] * x_low[dofmap_low(c, j)];
            }
            const std::int32_t g = dofmap_high(c, i);
            if (g < ndofs_high) // skip ghost dofs (none in serial)
            {
                x_high[g] += sum;
                mult[g] += 1.0;
            }
        }
    }

    // Average: every cell gave the same value, so dividing by the count recovers it
    for (std::int32_t g = 0; g < ndofs_high; ++g)
        x_high[g] /= mult[g];

    return x_high;
}

// Transpoing the x vector 
std::vector<double> apply_transfer_transpose(const std::vector<double>& x_high, const std::vector<double>& interp_folded, const permutation_class& pc, int nd_low, int nd_high, auto dofmap_low, auto dofmap_high, std::int32_t ndofs_low)
{
    const std::size_t n_cells = pc.clas.size();
    const std::int32_t ndofs_high = x_high.size();

    std::vector<double> mult(ndofs_high, 0.0);
    for (std::size_t c = 0; c < n_cells; ++c)
        for (int i = 0; i < nd_high; ++i)
        {
            const std::int32_t g = dofmap_high(c, i);
            if (g < ndofs_high)
                mult[g] += 1.0;
        }

    std::vector<double> x_scaled(ndofs_high);
    for (std::int32_t g = 0; g < ndofs_high; ++g)
        x_scaled[g] = x_high[g] / mult[g];

    std::vector<double> x_low(ndofs_low, 0.0);
    for (std::size_t c = 0; c < n_cells; ++c)
    {
        int p = pc.clas[c]; // permutation class of cell c
        for (int j = 0; j < nd_low; ++j) // Low-order dof (output)
        {
            double sum = 0.0;
            for (int i = 0; i < nd_high; ++i) // High-order dof (input): column j of interp_folded
            {
                const std::int32_t g = dofmap_high(c, i);
                if (g < ndofs_high)
                    sum += interp_folded[(p * nd_high + i) * nd_low + j] * x_scaled[g];
            }
            x_low[dofmap_low(c, j)] += sum;
        }
    }
    return x_low;
}

std::vector<double> discrete_gradient_reference(const basix::FiniteElement<double>& element_h1,
                                                const basix::FiniteElement<double>& element_curl)
{
    //Get Nedelec points and tabulate H1 basis functions at those points
    const auto [pts, pts_shape] = element_curl.points();
    const std::size_t nq = pts_shape[0];

    // Get 1st Derivative of basis functions, i.e. gradient. tabh1 is derivative or H1.
    auto [tab, tab_shape] = element_h1.tabulate(1, pts, pts_shape);
    basix::impl::mdspan_t<const double, 4> tab_h1(tab.data(), tab_shape);
    const std::size_t n_h1 = tab_shape[2];

    const auto [M, M_shape] = element_curl.interpolation_matrix();
    const std::size_t n_curl = M_shape[0];

    std::vector<double> G_ref(n_curl * n_h1, 0.0);
    for (std::size_t i = 0; i < n_curl; ++i)          
        for (std::size_t j = 0; j < n_h1; ++j)        
            for (std::size_t d = 0; d < 3; ++d)       
                for (std::size_t q = 0; q < nq; ++q)  
                    G_ref[i * n_h1 + j] += M[i * M_shape[1] + d * nq + q] * tab_h1(1 + d, q, j, 0);

    return G_ref;
}


struct level{
    std::shared_ptr<dolfinx::fem::FunctionSpace<double>> V;
    int elem_dim;
    std::int32_t ndofs;
    std::vector<double> folded;
    dolfinx::md::mdspan<const std::int32_t,
                        dolfinx::md::dextents<std::size_t, 2>> dofmap;
    std::vector<double> bc_mask;
};

level build_level(auto msh, const permutation_class& pc, int degree)
{
    level L;

    auto element = basix::create_element<double>(
        basix::element::family::N1E, basix::cell::type::tetrahedron, degree,
        basix::element::lagrange_variant::legendre, basix::element::dpc_variant::unset, false);
    
    L.elem_dim = element.dim();
    
    std::vector<double> refs = curlcurl_reference_matrix(element, 2 * degree + 2);
    std::vector<double> Tdense = dense_transform(element, pc.uniq, false);
    std::vector<double> Ttdense = dense_transform(element, pc.uniq, true);
    std::vector<double> folded = fold_reference(refs, Tdense, Ttdense, pc.uniq.size(), L.elem_dim );

    auto fe = std::make_shared<const dolfinx::fem::FiniteElement<double>>(element, msh->geometry().dim());
    
    L.folded = folded;
    L.V = std::make_shared<dolfinx::fem::FunctionSpace<double>>(dolfinx::fem::create_functionspace<double>(msh, fe));
    L.dofmap = L.V->dofmap()->map();
    L.ndofs = L.V->dofmap()->index_map->size_local();
    L.bc_mask = boundary_dof_mask(msh, L.V, L.ndofs);


    return L;
}

struct transfer{
    std::vector<double> interp_ref;
    std::vector<double> Ts;
    std::vector<double> Td;
    std::vector<double> interp_folded;
};

transfer build_transfer(int degree_low, int degree_high, const permutation_class& pc)
{
    transfer T;

    auto e_low = basix::create_element<double>(
        basix::element::family::N1E, basix::cell::type::tetrahedron, degree_low,
        basix::element::lagrange_variant::legendre, basix::element::dpc_variant::unset, false);
    auto e_high = basix::create_element<double>(
        basix::element::family::N1E, basix::cell::type::tetrahedron, degree_high,
        basix::element::lagrange_variant::legendre, basix::element::dpc_variant::unset, false);

    T.interp_ref = reference_interpolation(e_low, e_high);
    T.Ts = dense_transform(e_low, pc.uniq, true);
    T.Td = dense_transform_inv(e_high, pc.uniq);
    T.interp_folded = fold_interpolation(T.interp_ref, T.Ts, T.Td, pc.uniq.size(), e_low.dim(), e_high.dim());

    return T;
}

struct operator_data{
    // We want the data which does the Matvec at each level
    const level* L;
    const std::vector<double>* coeffs;
    const permutation_class* pc;
}; 

PetscErrorCode op_mult(Mat A, Vec x, Vec y)
{
    operator_data* data;
    PetscCall(MatShellGetContext(A, &data));
    const level* L = data->L;
    const std::vector<double>* coeffs = data->coeffs;
    const permutation_class* pc = data->pc;

    const PetscScalar* x_array;
    PetscCall(VecGetArrayRead(x, &x_array));
    std::vector<double> x_vec(x_array, x_array + L->ndofs);
    PetscCall(VecRestoreArrayRead(x, &x_array));

    std::vector<double> y_vec = matvec_bc(x_vec, L->bc_mask, *coeffs, *pc, L->elem_dim, L->folded, L->dofmap);

    PetscScalar* y_array;
    PetscCall(VecGetArray(y, &y_array));
    std::copy(y_vec.begin(), y_vec.end(), y_array);
    PetscCall(VecRestoreArray(y, &y_array));

    return PETSC_SUCCESS;

}

// d = diag(A): PETSc calls this (MATOP_GET_DIAGONAL) for the Jacobi / Chebyshev smoother
PetscErrorCode op_diag(Mat A, Vec d)
{
    operator_data* data;
    PetscCall(MatShellGetContext(A, &data));
    const level* L = data->L;

    std::vector<double> d_vec = diagonal_bc(L->bc_mask, *data->coeffs, *data->pc, L->elem_dim,
                                            L->folded, L->dofmap, L->ndofs);

    PetscScalar* d_array;
    PetscCall(VecGetArray(d, &d_array));
    std::copy(d_vec.begin(), d_vec.end(), d_array);
    PetscCall(VecRestoreArray(d, &d_array));

    return PETSC_SUCCESS;
}

struct transfer_data{
    // The data to move a vector between two neighbouring levels
    const level* L_low;
    const level* L_high;
    const transfer* T;
    const permutation_class* pc;
};

// y_high = P x_low (prolongation). PETSc calls this (MATOP_MULT) to move a coarse correction up.
// Boundary dofs are zeroed on both sides, so a correction never changes the Dirichlet dofs.
PetscErrorCode interp_mult(Mat P, Vec x, Vec y)
{
    transfer_data* data;
    PetscCall(MatShellGetContext(P, &data));
    const level* Lo = data->L_low;
    const level* Hi = data->L_high;

    const PetscScalar* x_array;
    PetscCall(VecGetArrayRead(x, &x_array));
    std::vector<double> x_vec(x_array, x_array + Lo->ndofs);
    PetscCall(VecRestoreArrayRead(x, &x_array));
    for (std::int32_t g = 0; g < Lo->ndofs; ++g) x_vec[g] *= 1.0 - Lo->bc_mask[g];

    std::vector<double> y_vec = apply_transfer(x_vec, data->T->interp_folded, *data->pc,
                                               Lo->elem_dim, Hi->elem_dim, Lo->dofmap, Hi->dofmap, Hi->ndofs);
    for (std::int32_t g = 0; g < Hi->ndofs; ++g) y_vec[g] *= 1.0 - Hi->bc_mask[g];

    PetscScalar* y_array;
    PetscCall(VecGetArray(y, &y_array));
    std::copy(y_vec.begin(), y_vec.end(), y_array);
    PetscCall(VecRestoreArray(y, &y_array));

    return PETSC_SUCCESS;
}

// y_low = P^T x_high (restriction). PETSc calls this (MATOP_MULT_TRANSPOSE) to move a residual down.
// Same masks as interp_mult, in the opposite order, so this is exactly its transpose.
PetscErrorCode interp_mult_transpose(Mat P, Vec x, Vec y)
{
    transfer_data* data;
    PetscCall(MatShellGetContext(P, &data));
    const level* Lo = data->L_low;
    const level* Hi = data->L_high;

    const PetscScalar* x_array;
    PetscCall(VecGetArrayRead(x, &x_array));
    std::vector<double> x_vec(x_array, x_array + Hi->ndofs);
    PetscCall(VecRestoreArrayRead(x, &x_array));
    for (std::int32_t g = 0; g < Hi->ndofs; ++g) x_vec[g] *= 1.0 - Hi->bc_mask[g];

    std::vector<double> y_vec = apply_transfer_transpose(x_vec, data->T->interp_folded, *data->pc,
                                                         Lo->elem_dim, Hi->elem_dim, Lo->dofmap, Hi->dofmap, Lo->ndofs);
    for (std::int32_t g = 0; g < Lo->ndofs; ++g) y_vec[g] *= 1.0 - Lo->bc_mask[g];

    PetscScalar* y_array;
    PetscCall(VecGetArray(y, &y_array));
    std::copy(y_vec.begin(), y_vec.end(), y_array);
    PetscCall(VecRestoreArray(y, &y_array));

    return PETSC_SUCCESS;
}

// ---- Test helpers: copy between PETSc Vec and std::vector ----
std::vector<double> to_std(Vec v)
{
    PetscInt n;
    const PetscScalar* a;
    PetscCallAbort(PETSC_COMM_SELF, VecGetLocalSize(v, &n));
    PetscCallAbort(PETSC_COMM_SELF, VecGetArrayRead(v, &a));
    std::vector<double> out(a, a + n);
    PetscCallAbort(PETSC_COMM_SELF, VecRestoreArrayRead(v, &a));
    return out;
}

Vec to_petsc(const std::vector<double>& s)
{
    Vec v;
    PetscScalar* a;
    PetscCallAbort(PETSC_COMM_SELF, VecCreateSeq(PETSC_COMM_SELF, s.size(), &v));
    PetscCallAbort(PETSC_COMM_SELF, VecGetArray(v, &a));
    std::copy(s.begin(), s.end(), a);
    PetscCallAbort(PETSC_COMM_SELF, VecRestoreArray(v, &a));
    return v;
}

double max_diff(const std::vector<double>& a, const std::vector<double>& b)
{
    double m = 0.0;
    for (std::size_t i = 0; i < a.size(); ++i)
        m = std::max(m, std::abs(a[i] - b[i]));
    return m;
}

struct ams_data{
    Mat A0;                      // assembled level-0 operator (from the UFL form in curlcurl.py)
    Mat G0;                      // assembled discrete gradient, (level-0 ndofs) x (P1 ndofs)
    std::vector<double> coords;  // P1 dof coordinates, (P1 ndofs, 3) row-major
};

PetscErrorCode build_ams_data(auto msh, const permutation_class& pc, const level& L0, ams_data& ams)
{
    auto a = dolfinx::fem::create_form<PetscScalar>(*form_curlcurl_a, {L0.V, L0.V}, {}, {}, {}, {});
    ams.A0 = dolfinx::fem::petsc::create_matrix(a);
    PetscCall(MatZeroEntries(ams.A0));

    std::vector<std::int8_t> bc_marker(L0.bc_mask.begin(), L0.bc_mask.end());
    dolfinx::fem::assemble_matrix(dolfinx::la::petsc::Matrix::set_block_fn(ams.A0, ADD_VALUES), a,
                                  bc_marker, bc_marker);
    for (std::int32_t g = 0; g < L0.ndofs; ++g)
        if (bc_marker[g])
            PetscCall(MatSetValue(ams.A0, g, g, 1.0, ADD_VALUES));
    PetscCall(MatAssemblyBegin(ams.A0, MAT_FINAL_ASSEMBLY));
    PetscCall(MatAssemblyEnd(ams.A0, MAT_FINAL_ASSEMBLY));

    auto e_p1 = basix::create_element<double>(
        basix::element::family::P, basix::cell::type::tetrahedron, 1,
        basix::element::lagrange_variant::gll_warped, basix::element::dpc_variant::unset, false);
    auto e_n1 = basix::create_element<double>(
        basix::element::family::N1E, basix::cell::type::tetrahedron, 1,
        basix::element::lagrange_variant::legendre, basix::element::dpc_variant::unset, false);
    auto fe_p1 = std::make_shared<const dolfinx::fem::FiniteElement<double>>(e_p1, msh->geometry().dim());
    auto V_p1 = std::make_shared<dolfinx::fem::FunctionSpace<double>>(
                    dolfinx::fem::create_functionspace<double>(msh, fe_p1));
    auto dofmap_p1 = V_p1->dofmap()->map();
    const PetscInt n_p1 = V_p1->dofmap()->index_map->size_local();
    ams.coords = V_p1->tabulate_dof_coordinates(false);

    // 3. Folded gradient per permutation class (same recipe as the degree-3 gradient in main)
    const int nd_p1 = e_p1.dim();  // 4
    const int nd_n1 = e_n1.dim();  // 6
    const std::size_t n_class = pc.uniq.size();
    std::vector<double> G_ref = discrete_gradient_reference(e_p1, e_n1);
    std::vector<double> Ts(n_class * nd_p1 * nd_p1, 0.0);  // identity: the dofmap handles Lagrange
    for (std::size_t p = 0; p < n_class; ++p)
        for (int i = 0; i < nd_p1; ++i)
            Ts[p * nd_p1 * nd_p1 + i * nd_p1 + i] = 1.0;
    std::vector<double> Td = dense_transform_inv(e_n1, pc.uniq);
    std::vector<double> G_folded = fold_interpolation(G_ref, Ts, Td, n_class, nd_p1, nd_n1);

    PetscCall(MatCreateSeqAIJ(PETSC_COMM_SELF, L0.ndofs, n_p1, nd_p1, nullptr, &ams.G0));
    const std::size_t n_cells = dofmap_p1.extent(0);
    for (std::size_t c = 0; c < n_cells; ++c)
    {
        const std::int32_t p = pc.clas[c];
        for (int i = 0; i < nd_n1; ++i)
            for (int j = 0; j < nd_p1; ++j)
            {
                const double v = G_folded[(p * nd_n1 + i) * nd_p1 + j];
                if (std::abs(v) > 1e-12)
                    PetscCall(MatSetValue(ams.G0, L0.dofmap(c, i), dofmap_p1(c, j), v, INSERT_VALUES));
            }
    }
    PetscCall(MatAssemblyBegin(ams.G0, MAT_FINAL_ASSEMBLY));
    PetscCall(MatAssemblyEnd(ams.G0, MAT_FINAL_ASSEMBLY));

    return PETSC_SUCCESS;
}

struct gradient{
    std::shared_ptr<dolfinx::fem::FunctionSpace<double>> V;   // Lagrange space
    int elem_dim;                                             // Lagrange dofs per cell
    std::int32_t ndofs;                                       // Lagrange global dofs
    std::vector<double> folded;                               // folded G, (n_class, nd_curl, nd_h1)
    dolfinx::md::mdspan<const std::int32_t,
                        dolfinx::md::dextents<std::size_t, 2>> dofmap;   // Lagrange dofmap
    std::vector<double> bc_mask;                              // 1 on boundary Lagrange dofs
};

gradient build_gradient(auto msh, const permutation_class& pc, int degree)
{
    gradient G;

    auto e_h1 = basix::create_element<double>(
        basix::element::family::P, basix::cell::type::tetrahedron, degree,
        basix::element::lagrange_variant::gll_warped, basix::element::dpc_variant::unset, false);
    auto e_curl = basix::create_element<double>(
        basix::element::family::N1E, basix::cell::type::tetrahedron, degree,
        basix::element::lagrange_variant::legendre, basix::element::dpc_variant::unset, false);

    auto fe_h1 = std::make_shared<const dolfinx::fem::FiniteElement<double>>(e_h1, msh->geometry().dim());
    G.V = std::make_shared<dolfinx::fem::FunctionSpace<double>>(
                    dolfinx::fem::create_functionspace<double>(msh, fe_h1));
    G.elem_dim = e_h1.dim();
    G.ndofs = G.V->dofmap()->index_map->size_local();
    G.dofmap = G.V->dofmap()->map();
    G.bc_mask = boundary_dof_mask(msh, G.V, G.ndofs);

    const int nd_curl = e_curl.dim();
    const int nd_h1 = e_h1.dim();
    const std::size_t n_class = pc.uniq.size();
    std::vector<double> G_ref = discrete_gradient_reference(e_h1, e_curl);   // (nd_curl, nd_h1)
    std::vector<double> Ts(n_class * nd_h1 * nd_h1, 0.0);  // identity: the dofmap handles Lagrange
    for (std::size_t p = 0; p < n_class; ++p)
        for (int i = 0; i < nd_h1; ++i)
            Ts[p * nd_h1 * nd_h1 + i * nd_h1 + i] = 1.0;
    std::vector<double> Td = dense_transform_inv(e_curl, pc.uniq);
    G.folded = fold_interpolation(G_ref, Ts, Td, n_class, nd_h1, nd_curl);

    return G;
}


std::vector<double> apply_G(const std::vector<double>& u_h1, const gradient& Gr,
                            const level& L, const permutation_class& pc)
{
    std::vector<double> u_masked = u_h1;
    for (std::int32_t j = 0; j < Gr.ndofs; ++j)
        u_masked[j] *= 1.0 - Gr.bc_mask[j];

    std::vector<double> g = apply_transfer(u_masked, Gr.folded, pc, Gr.elem_dim, L.elem_dim,
                                           Gr.dofmap, L.dofmap, L.ndofs);

    for (std::int32_t n = 0; n < L.ndofs; ++n)
        g[n] *= 1.0 - L.bc_mask[n];

    return g;
}

// Applies transpose of discrete gradient
std::vector<double> apply_Gt(const std::vector<double>& r_curl, const gradient& Gr,
                             const level& L, const permutation_class& pc)
{

    std::vector<double> r_masked = r_curl;
    for (std::int32_t n = 0; n < L.ndofs; ++n)
        r_masked[n] *= 1.0 - L.bc_mask[n];

    std::vector<double> gt = apply_transfer_transpose(r_masked, Gr.folded, pc, Gr.elem_dim, L.elem_dim,
                                                        Gr.dofmap, L.dofmap, Gr.ndofs);

    for (std::int32_t j = 0; j < Gr.ndofs; ++j)
        gt[j] *= 1.0 - Gr.bc_mask[j];

    return gt;
}

PetscErrorCode setup_ams_coarse(KSP coarse, ams_data& ams)
{
    PC coarse_pc;
    PetscCall(KSPSetOperators(coarse, ams.A0, ams.A0));
    PetscCall(KSPSetType(coarse, KSPCG));
    PetscCall(KSPSetTolerances(coarse, 1e-10, PETSC_DEFAULT, PETSC_DEFAULT, 100));

    PetscCall(KSPGetPC(coarse, &coarse_pc));
    PetscCall(PCSetType(coarse_pc, PCHYPRE));
    PetscCall(PCHYPRESetType(coarse_pc, "ams"));
    PetscCall(PCHYPRESetDiscreteGradient(coarse_pc, ams.G0));
    PetscCall(PCSetCoordinates(coarse_pc, 3, ams.coords.size() / 3, ams.coords.data()));

    return PETSC_SUCCESS;
}

//   D_n[j] += g_j^T · A_c · g_j      (g_j = column j of the cell's gradient, A_c = cell matrix)
std::vector<double> diag_gtAg(const gradient& G, const level& L,
                              const std::vector<double>& coeffs, const permutation_class& pc)
{
    std::vector<double> D_n(G.ndofs, 0.0);

    const int nd    = L.elem_dim;    // Nedelec dofs per cell
    const int nd_h1 = G.elem_dim;    // Lagrange dofs per cell
    std::vector<double> A_c(nd * nd);        // cell matrix
    std::vector<double> G_c(nd * nd_h1);     // discrete gradient cell wise
    std::vector<double> W(nd * nd_h1);       // interemdiate product A_c · G_c

    for (std::size_t c = 0; c < pc.clas.size(); ++c)
    {
        const int p = pc.clas[c];

        std::fill(A_c.begin(), A_c.end(), 0.0);
        for (int k = 0; k < 12; ++k)
            for (int i = 0; i < nd; ++i)
                for (int m = 0; m < nd; ++m)
                    A_c[i * nd + m] += coeffs[12 * c + k] * L.folded[((p * 12 + k) * nd + i) * nd + m];

        for (int m = 0; m < nd; ++m)
            for (int j = 0; j < nd_h1; ++j)
                G_c[m * nd_h1 + j] = G.folded[(p * nd + m) * nd_h1 + j]
                                     * (1.0 - L.bc_mask[L.dofmap(c, m)]);

        // W = A_c · G_c
        for (int i = 0; i < nd; ++i)
            for (int j = 0; j < nd_h1; ++j)
            {
                double sum = 0.0;
                for (int m = 0; m < nd; ++m)
                    sum += A_c[i * nd + m] * G_c[m * nd_h1 + j];
                W[i * nd_h1 + j] = sum;
            }

        for (int j = 0; j < nd_h1; ++j)
        {
            double sum = 0.0;
            for (int i = 0; i < nd; ++i)
                sum += G_c[i * nd_h1 + j] * W[i * nd_h1 + j];
            D_n[G.dofmap(c, j)] += sum;
        }
    }

    for (std::int32_t j = 0; j < G.ndofs; ++j)
        if (G.bc_mask[j] == 1.0)
            D_n[j] = 1.0;

    return D_n;
}




int main(int argc, char* argv[])
{
    PetscInitialize(&argc, &argv, nullptr, nullptr);
    dolfinx::init_logging(argc, argv);
    {
        auto msh = std::make_shared<dolfinx::mesh::Mesh<double>>(
            dolfinx::mesh::create_box<double>(
                MPI_COMM_WORLD, {{{0.0, 0.0, 0.0}, {1.0, 1.0, 1.0}}}, {4, 4, 4},
                dolfinx::mesh::CellType::tetrahedron));

        // ---- Mesh-only data: the same on every level ----
        std::vector<double> coeffs = piola_map(msh); // (n_cells, 12): 6 curl-curl then 6 mass
        permutation_class pc = permutation_classes(msh);
        // std::cout << "permutation classes: " << pc.uniq.size() << "\n";

        // ---- Levels: index 0 = degree 1 (coarsest) ... index 2 = degree 3 (finest) ----
        std::vector<level> levels;
        for (int degree = 1; degree <= 3; ++degree)
            levels.push_back(build_level(msh, pc, degree));
        
        // Create discrete gradietn

        std::vector<gradient> gradients;
        for (int degree = 1; degree <= 3; ++degree)
            gradients.push_back(build_gradient(msh, pc, degree));

        // Test: operator and diagonal (with BCs) on every level
        for (std::size_t l = 0; l < levels.size(); ++l)
        {
            const level& L = levels[l];
            std::vector<double> x(L.ndofs, 1.0);
            std::vector<double> y = matvec_bc(x, L.bc_mask, coeffs, pc, L.elem_dim, L.folded, L.dofmap);
            std::vector<double> d = diagonal_bc(L.bc_mask, coeffs, pc, L.elem_dim, L.folded, L.dofmap, L.ndofs);
            std::cout << "level " << l << ": degree " << l + 1 << ", " << L.elem_dim << " dofs/cell, "
                      << L.ndofs << " dofs, "
                      << std::count(L.bc_mask.begin(), L.bc_mask.end(), 1.0) << " boundary dofs\n";
        }

        level& L_low = levels[0];
        level& L_high = levels[1];
        gradient G = build_gradient(msh, pc, 1);

        std::vector<int> degrees = {1, 2, 3};
        std::vector<transfer> transfers;

        for (int i = 0; i < degrees.size() - 1; i ++){
            transfer T = build_transfer(degrees[i], degrees[i+1], pc);
            transfers.push_back(T);
        }


        // Test: transfer a low-order vector up to the high-order space
        std::vector<double> x_low(L_low.ndofs);
        for (std::int32_t g = 0; g < L_low.ndofs; ++g) x_low[g] = std::sin(g);
        std::vector<double> x_high = apply_transfer(x_low, transfers[0].interp_folded, pc, L_low.elem_dim, L_high.elem_dim,
                                                    L_low.dofmap, L_high.dofmap, L_high.ndofs);
        // std::cout << "transfer: " << L_low.ndofs << " low dofs -> " << x_high.size() << " high dofs\n";

        // Test: restrict a high-order vector down to the low-order space
        std::vector<double> r_high(L_high.ndofs);
        for (std::int32_t g = 0; g < L_high.ndofs; ++g) r_high[g] = std::cos(g);
        std::vector<double> r_low = apply_transfer_transpose(r_high, transfers[0].interp_folded, pc, L_low.elem_dim, L_high.elem_dim,
                                                             L_low.dofmap, L_high.dofmap, L_low.ndofs);
        // std::cout << "restriction: " << L_high.ndofs << " high dofs -> " << r_low.size() << " low dofs\n";

        // ---- Discrete gradient: Lagrange P3 -> Nedelec degree 3 (levels[2]) ----
        const level& L_fine = levels[2];
        auto element_curl = basix::create_element<double>(
            basix::element::family::N1E, basix::cell::type::tetrahedron, 3,
            basix::element::lagrange_variant::legendre, basix::element::dpc_variant::unset, false);
        auto element_h1 = basix::create_element<double>(
            basix::element::family::P, basix::cell::type::tetrahedron, 3,
            basix::element::lagrange_variant::gll_warped, basix::element::dpc_variant::unset, false);
        const int nd_h1 = element_h1.dim(); // 20

        // Reference gradient matrix, shape (45, 20)
        std::vector<double> grad_ref = discrete_gradient_reference(element_h1, element_curl);

        // Lagrange side needs no transform (the dofmap handles it), so Ts is the identity
        std::vector<double> Ts_h1(pc.uniq.size() * nd_h1 * nd_h1, 0.0);
        for (std::size_t p = 0; p < pc.uniq.size(); ++p)
            for (int i = 0; i < nd_h1; ++i)
                Ts_h1[p * nd_h1 * nd_h1 + i * nd_h1 + i] = 1.0;
        std::vector<double> Td_curl = dense_transform_inv(element_curl, pc.uniq);
        std::vector<double> grad_folded = fold_interpolation(grad_ref, Ts_h1, Td_curl, pc.uniq.size(),
                                                             nd_h1, L_fine.elem_dim);

        // Lagrange function space for the source dofmap
        auto fe_h1 = std::make_shared<const dolfinx::fem::FiniteElement<double>>(element_h1, msh->geometry().dim());
        auto V_h1  = std::make_shared<dolfinx::fem::FunctionSpace<double>>(
                         dolfinx::fem::create_functionspace<double>(msh, fe_h1));
        auto dofmap_h1 = V_h1->dofmap()->map();
        const std::int32_t ndofs_h1 = V_h1->dofmap()->index_map->size_local();

        // Test: gradient of an H1 vector
        std::vector<double> u_h1(ndofs_h1);
        for (std::int32_t g = 0; g < ndofs_h1; ++g) u_h1[g] = std::sin(g);
        std::vector<double> grad_u = apply_transfer(u_h1, grad_folded, pc, nd_h1, L_fine.elem_dim,
                                                    dofmap_h1, L_fine.dofmap, L_fine.ndofs);
        // std::cout << "discrete gradient: " << ndofs_h1 << " H1 dofs -> " << grad_u.size() << " H(curl) dofs\n";

        
        std::vector<operator_data> op_data(levels.size());
        std::vector<Mat> A(levels.size());
        for (std::size_t l = 0; l < levels.size(); ++l)
        {
            op_data[l] = {&levels[l], &coeffs, &pc};
            const PetscInt n = levels[l].ndofs;
            // A matrix that stores no values: PETSc calls op_mult / op_diag instead
            PetscCall(MatCreateShell(PETSC_COMM_SELF, n, n, n, n, &op_data[l], &A[l]));
            PetscCall(MatShellSetOperation(A[l], MATOP_MULT, (void (*)(void))op_mult));
            PetscCall(MatShellSetOperation(A[l], MATOP_GET_DIAGONAL, (void (*)(void))op_diag));
        }

        std::vector<transfer_data> tr_data(transfers.size());
        std::vector<Mat> P(transfers.size());
        for (std::size_t l = 0; l < transfers.size(); ++l)
        {
            tr_data[l] = {&levels[l], &levels[l + 1], &transfers[l], &pc};
            const PetscInt n_low  = levels[l].ndofs;
            const PetscInt n_high = levels[l + 1].ndofs;
            
            // Create Petsc matrix that holds a pointer to tr_data.
            PetscCall(MatCreateShell(PETSC_COMM_SELF, n_high, n_low, n_high, n_low, &tr_data[l], &P[l]));
            PetscCall(MatShellSetOperation(P[l], MATOP_MULT, (void (*)(void))interp_mult));
            PetscCall(MatShellSetOperation(P[l], MATOP_MULT_TRANSPOSE, (void (*)(void))interp_mult_transpose));
        }

        for (std::size_t l = 0; l < levels.size(); ++l)
        {
            const level& L = levels[l];
            std::vector<double> xs(L.ndofs);
            for (std::int32_t g = 0; g < L.ndofs; ++g) xs[g] = std::sin(g);

            Vec xv = to_petsc(xs), yv, dv;
            PetscCall(VecDuplicate(xv, &yv));
            PetscCall(VecDuplicate(xv, &dv));
            PetscCall(MatMult(A[l], xv, yv));
            PetscCall(MatGetDiagonal(A[l], dv));

            std::vector<double> y_ref = matvec_bc(xs, L.bc_mask, coeffs, pc, L.elem_dim, L.folded, L.dofmap);
            std::vector<double> d_ref = diagonal_bc(L.bc_mask, coeffs, pc, L.elem_dim, L.folded, L.dofmap, L.ndofs);
            // std::cout << "A[" << l << "]: MatMult diff = " << max_diff(to_std(yv), y_ref)
                      // << ", MatGetDiagonal diff = " << max_diff(to_std(dv), d_ref) << "\n";

            PetscCall(VecDestroy(&xv));
            PetscCall(VecDestroy(&yv));
            PetscCall(VecDestroy(&dv));
        }

        // ---- Test: each P[l] must match apply_transfer, and MatMultTranspose must be its exact transpose ----
        for (std::size_t l = 0; l < transfers.size(); ++l)
        {
            const level& Lo = levels[l];
            const level& Hi = levels[l + 1];
            std::vector<double> xs(Lo.ndofs), ys(Hi.ndofs);
            for (std::int32_t g = 0; g < Lo.ndofs; ++g) xs[g] = std::sin(g);
            for (std::int32_t g = 0; g < Hi.ndofs; ++g) ys[g] = std::cos(g);

            Vec xl = to_petsc(xs), yh = to_petsc(ys), Px, PTy;
            PetscCall(VecDuplicate(yh, &Px));
            PetscCall(VecDuplicate(xl, &PTy));
            PetscCall(MatMult(P[l], xl, Px));
            PetscCall(MatMultTranspose(P[l], yh, PTy));

            // Reference: apply_transfer with the same boundary masking as interp_mult
            std::vector<double> xm = xs;
            for (std::int32_t g = 0; g < Lo.ndofs; ++g) xm[g] *= 1.0 - Lo.bc_mask[g];
            std::vector<double> Px_ref = apply_transfer(xm, transfers[l].interp_folded, pc, Lo.elem_dim, Hi.elem_dim,
                                                        Lo.dofmap, Hi.dofmap, Hi.ndofs);
            for (std::int32_t g = 0; g < Hi.ndofs; ++g) Px_ref[g] *= 1.0 - Hi.bc_mask[g];

            // Transpose check: (P x) . y must equal x . (P^T y)
            PetscScalar Px_dot_y, x_dot_PTy;
            PetscCall(VecDot(Px, yh, &Px_dot_y));
            PetscCall(VecDot(xl, PTy, &x_dot_PTy));

            // std::cout << "P[" << l << "] (degree " << l + 1 << " -> " << l + 2 << "): MatMult diff = "
                      // << max_diff(to_std(Px), Px_ref)
                      // << ", |Px.y - x.PTy| = " << std::abs(Px_dot_y - x_dot_PTy) << "\n";

            PetscCall(VecDestroy(&xl));
            PetscCall(VecDestroy(&yh));
            PetscCall(VecDestroy(&Px));
            PetscCall(VecDestroy(&PTy));
        }

        KSP ksp;
        PC pc_mg;

        PetscCall(KSPCreate(PETSC_COMM_SELF, &ksp));
        PetscCall(KSPSetOperators(ksp, A[2], A[2])); // Use the finest level operator
        PetscCall(KSPGetPC(ksp, &pc_mg));
        PetscCall(PCSetType(pc_mg, PCMG));

        PetscCall(PCMGSetLevels(pc_mg, levels.size(), nullptr));

        // Data for the AMS coarse solve: assembled A0, assembled G (P1 -> N1E degree 1), coordinates
        ams_data ams;
        PetscCall(build_ams_data(msh, pc, levels[0], ams));

    // Multigrid setup
    for (int l = 0; l < levels.size(); ++l)
        {
            KSP smoother;
            PC smoother_pc;
            PetscCall(PCMGGetSmoother(pc_mg, l, &smoother));
            PetscCall(KSPSetOperators(smoother, A[l], A[l]));
            PetscCall(KSPGetPC(smoother, &smoother_pc));
            PetscCall(PCSetType(smoother_pc, PCJACOBI));

            if (l == 0)
            {
                // Coarsest level: CG + hypre AMS on the assembled degree-1 operator
                PetscCall(setup_ams_coarse(smoother, ams));
            }
            else
            {
                PetscCall(KSPSetType(smoother, KSPCHEBYSHEV));
                PetscCall(KSPChebyshevEstEigSet(smoother, PETSC_DETERMINE, PETSC_DETERMINE,
                                                PETSC_DETERMINE, PETSC_DETERMINE));
            }
        }

        for (int l = 1; l < levels.size(); ++l)
            PetscCall(PCMGSetInterpolation(pc_mg, l, P[l - 1]));


        PetscCall(KSPSetType(ksp, KSPFCG));
        PetscCall(KSPSetTolerances(ksp, 1e-8, PETSC_DEFAULT, PETSC_DEFAULT, 500));
        PetscCall(KSPSetFromOptions(ksp));

        const level& L_solve = levels[2];
        std::vector<double> b_vec(L_solve.ndofs, 1.0);
        for (std::int32_t g = 0; g < L_solve.ndofs; ++g)
            if (L_solve.bc_mask[g] == 1.0) b_vec[g] = 0.0;   // u = 0 on the boundary
        Vec b = to_petsc(b_vec);
        Vec u;
        PetscCall(VecDuplicate(b, &u));

        PetscCall(KSPSolve(ksp, b, u));

        KSPConvergedReason reason;
        PetscInt iterations;
        PetscReal residual;
        PetscCall(KSPGetConvergedReason(ksp, &reason));
        PetscCall(KSPGetIterationNumber(ksp, &iterations));
        PetscCall(KSPGetResidualNorm(ksp, &residual));
        std::cout << "PMG solve: " << KSPConvergedReasons[reason] << " in " << iterations
                  << " iterations, residual norm " << residual << "\n";

        PetscCall(VecDestroy(&b));
        PetscCall(VecDestroy(&u));

        PetscCall(KSPDestroy(&ksp));
        for (Mat& M : A) PetscCall(MatDestroy(&M));
        for (Mat& M : P) PetscCall(MatDestroy(&M));
        PetscCall(MatDestroy(&ams.A0));
        PetscCall(MatDestroy(&ams.G0));
    }
    PetscFinalize();
    return 0;
}
